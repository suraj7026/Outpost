class Refused(RuntimeError):
    """A fixed, non-secret reason code; never include untrusted file content."""


def need(condition: object, code: str) -> None:
    if not condition:
        raise Refused(code)


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def hash_value(value: object) -> str:
    if not isinstance(value, str) or not re.fullmatch('[0-9a-f]{64}', value):
        raise Refused('invalid_sha256')
    return value


def path_name(value: object) -> str:
    """A unique POSIX archive/path spelling, never a traversal or control string."""
    if not isinstance(value, str) or not 0 < len(value) <= 1024:
        raise Refused('invalid_path')
    need('\\' not in value and all(32 <= ord(c) < 127 for c in value), 'invalid_path')
    parts = value.split('/')
    need(len(parts) <= 64 and all(p not in ('', '.', '..') and len(p) <= 255 for p in parts),
         'invalid_path')
    return value


def document(data: bytes) -> dict:
    def unique(pairs: list) -> dict:
        result = {}
        for key, value in pairs:
            need(key not in result, 'duplicate_json_key')
            result[key] = value
        return result
    result = json.loads(data, object_pairs_hook=unique)
    need(type(result) is dict, 'json_object_required')
    return result


def fields(value: object, expected: set[str]) -> dict:
    if type(value) is not dict or set(value) != expected:
        raise Refused('unsupported_reference_contract')
    return value


def stamp(info: os.stat_result) -> tuple:
    return tuple(getattr(info, key) for key in ('st_dev', 'st_ino', 'st_mode', 'st_uid',
                 'st_gid', 'st_nlink', 'st_size', 'st_mtime_ns', 'st_ctime_ns'))


def stat_record(path: str, info: os.stat_result) -> dict:
    """Serializable identity/preconditions; atime is deliberately not an assertion."""
    return {'path': path, 'device': info.st_dev, 'inode': info.st_ino, 'uid': info.st_uid,
            'gid': info.st_gid, 'mode': stat.S_IMODE(info.st_mode), 'nlink': info.st_nlink,
            'size': info.st_size, 'mtimeNs': info.st_mtime_ns, 'ctimeNs': info.st_ctime_ns}


class Budget:
    """Shared limits include every reference and installed-content read."""

    def __init__(self) -> None:
        self.deadline = time.monotonic() + MAX_SECONDS
        self.bytes = self.expanded = self.nodes = 0

    def tick(self, *, size: int = 0, expanded: int = 0, nodes: int = 0) -> None:
        self.bytes += size
        self.expanded += expanded
        self.nodes += nodes
        need(time.monotonic() <= self.deadline, 'time_budget')
        need(self.bytes <= MAX_BYTES and self.expanded <= MAX_EXPANDED and
             self.nodes <= MAX_NODES, 'read_budget')


class Files:
    """Descriptor-relative no-follow reader with final namespace/stat rechecks."""

    def __init__(self, root: Path, budget: Budget) -> None:
        need(root.is_absolute() and '..' not in root.parts, 'absolute_root_required')
        self.root, self.budget = root, budget
        self.seen: dict[str, tuple] = {}
        self.fd, self.chain = self._anchor()

    def _anchor(self) -> tuple[int, list]:
        # Lookup/fstat of unlisted ancestors does not read directory contents.
        flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
        fd = os.open('/', flags)
        chain = []
        try:
            for part in self.root.parts[1:]:
                self.budget.tick()
                before = os.stat(part, dir_fd=fd, follow_symlinks=False)
                need(stat.S_ISDIR(before.st_mode), 'symlink_or_nondirectory_ancestor')
                child = os.open(part, flags, dir_fd=fd)
                try:
                    need(stamp(before) == stamp(os.fstat(child)), 'filesystem_changed')
                except BaseException:
                    os.close(child)
                    raise
                os.close(fd)
                fd = child
                chain.append(stamp(before))
            return fd, chain
        except BaseException:
            os.close(fd)
            raise

    def close(self) -> None:
        os.close(self.fd)

    def __enter__(self):
        return self

    def __exit__(self, *_exc) -> None:
        self.close()

    def remember(self, name: str, info: os.stat_result) -> None:
        value = stamp(info)
        need(self.seen.get(name, value) == value, 'filesystem_changed')
        self.seen[name] = value

    @contextmanager
    def directory(self, name: str):
        parts = path_name(name).split('/') if name else []
        fd = os.dup(self.fd)
        current = ''
        try:
            self.remember('', os.fstat(fd))
            for part in parts:
                self.budget.tick()
                current = current + '/' + part if current else part
                before = os.stat(part, dir_fd=fd, follow_symlinks=False)
                need(stat.S_ISDIR(before.st_mode), 'symlink_or_nondirectory_ancestor')
                child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=fd)
                try:
                    need(stamp(before) == stamp(os.fstat(child)), 'filesystem_changed')
                    self.remember(current, before)
                except BaseException:
                    os.close(child)
                    raise
                os.close(fd)
                fd = child
            yield fd
            self.remember(name, os.fstat(fd))
        finally:
            os.close(fd)

    def info(self, name: str) -> os.stat_result:
        path_name(name)
        parent, leaf = posixpath.split(name)
        with self.directory(parent) as fd:
            info = os.stat(leaf, dir_fd=fd, follow_symlinks=False)
            self.remember(name, info)
            return info

    def file(self, name: str, limit: int, *, keep: bool = True) -> tuple[bytes, dict]:
        """Hash an entire regular file, refusing shrink/growth and inode changes."""
        path_name(name)
        parent, leaf = posixpath.split(name)
        with self.directory(parent) as fd:
            before = os.stat(leaf, dir_fd=fd, follow_symlinks=False)
            need(stat.S_ISREG(before.st_mode), 'regular_file_required')
            need(0 <= before.st_size <= limit, 'file_size_limit')
            self.remember(name, before)
            child = os.open(leaf, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK |
                            getattr(os, 'O_NOATIME', 0), dir_fd=fd)
            try:
                need(stamp(before) == stamp(os.fstat(child)), 'filesystem_changed')
                digest, size, chunks = hashlib.sha256(), 0, []
                while True:
                    self.budget.tick()
                    data = os.read(child, min(1024 * 1024, limit - size + 1))
                    if not data:
                        break
                    size += len(data)
                    self.budget.tick(size=len(data))
                    need(size <= before.st_size, 'filesystem_changed')
                    digest.update(data)
                    if keep:
                        chunks.append(data)
                need(size == before.st_size and stamp(before) == stamp(os.fstat(child)),
                     'filesystem_changed')
                after = os.stat(leaf, dir_fd=fd, follow_symlinks=False)
                need(stamp(before) == stamp(after), 'filesystem_changed')
            finally:
                os.close(child)
        return b''.join(chunks), dict(stat_record(name, before), sha256=digest.hexdigest())

    def link(self, name: str) -> str:
        parent, leaf = posixpath.split(path_name(name))
        with self.directory(parent) as fd:
            before = os.stat(leaf, dir_fd=fd, follow_symlinks=False)
            need(stat.S_ISLNK(before.st_mode), 'symlink_required')
            self.remember(name, before)
            target = os.readlink(leaf, dir_fd=fd)
            need(stamp(before) == stamp(os.stat(leaf, dir_fd=fd, follow_symlinks=False)),
                 'filesystem_changed')
            need(len(target) <= 1024, 'link_size_limit')
            return target

    def walk(self, name: str) -> dict[str, os.stat_result]:
        result = {name: self.info(name)}
        need(stat.S_ISDIR(result[name].st_mode), 'directory_required')

        def descend(current: str) -> None:
            with self.directory(current) as fd:
                children = []
                scan_fd = os.open('.', os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW |
                                  getattr(os, 'O_NOATIME', 0), dir_fd=fd)
                try:
                    need(stamp(os.fstat(scan_fd)) == stamp(os.fstat(fd)), 'filesystem_changed')
                    with os.scandir(scan_fd) as entries:
                        for entry in entries:
                            self.budget.tick(nodes=1)
                            path = path_name(current + '/' + entry.name)
                            info = os.stat(entry.name, dir_fd=fd, follow_symlinks=False)
                            self.remember(path, info)
                            need(stat.S_ISREG(info.st_mode) or stat.S_ISDIR(info.st_mode) or
                                 stat.S_ISLNK(info.st_mode), 'special_file')
                            result[path] = info
                            if stat.S_ISDIR(info.st_mode):
                                children.append(path)
                finally:
                    os.close(scan_fd)
                for child in sorted(children):
                    descend(child)
        descend(name)
        return result

    def recheck(self) -> None:
        fd, chain = self._anchor()
        try:
            need(chain == self.chain and stamp(os.fstat(fd)) == self.seen.get('', stamp(os.fstat(fd))),
                 'filesystem_changed')
        finally:
            os.close(fd)
        for name, expected in list(self.seen.items()):
            self.budget.tick()
            if name:
                need(stamp(self.info(name)) == expected, 'filesystem_changed')


class Reference(NamedTuple):
    """Artifact-derived expectation, not an installed RECORD assertion."""

    kind: str
    sha256: str = ''
    size: int = 0
    executable: bool = False
    target: str = ''


def regular(data: bytes, mode: int = 0o644) -> Reference:
    return Reference('file', sha(data), len(data), bool(mode & 0o111))


def insert(tree: dict[str, Reference], path: str, ref: Reference) -> None:
    path_name(path)
    need(path not in tree, 'reference_path_collision')
    tree[path] = ref


def parents(tree: dict[str, Reference]) -> None:
    for path in list(tree):
        parent = posixpath.dirname(path)
        while parent:
            need(parent not in tree or tree[parent].kind == 'dir', 'reference_parent_collision')
            tree.setdefault(parent, Reference('dir'))
            parent = posixpath.dirname(parent)


def tar_members(blob: bytes, budget: Budget) -> dict[str, tuple[tarfile.TarInfo, bytes]]:
    """Bound the decompressed stream (including headers), never extract to disk."""
    class Limited(io.RawIOBase):
        def __init__(self, stream):
            super().__init__()
            self.stream = stream

        def read(self, size: int = -1) -> bytes:
            need(0 <= size <= MAX_FILE, 'archive_read_limit')
            data = self.stream.read(size)
            budget.tick(expanded=len(data))
            return data

    result = {}
    with gzip.GzipFile(fileobj=io.BytesIO(blob)) as stream:
        with tarfile.open(fileobj=Limited(stream), mode='r|') as archive:
            for item in archive:
                budget.tick(nodes=1)
                name = item.name
                if name.startswith('./'):
                    name = name[2:]
                if item.isdir():
                    name = name.rstrip('/')
                    if name in ('', '.'):
                        continue
                path_name(name)
                need(name not in result, 'duplicate_archive_path')
                need(item.isfile() or item.isdir() or item.issym() or item.islnk(), 'archive_special_file')
                need(not item.sparse and not item.mode & 0o7000, 'unsupported_tar_metadata')
                need(0 <= item.size <= MAX_FILE, 'archive_member_limit')
                data = b''
                if item.isfile():
                    source = archive.extractfile(item)
                    if source is None:
                        raise Refused('archive_missing_content')
                    data = source.read(item.size + 1)
                    need(len(data) == item.size, 'archive_member_size')
                result[name] = item, data
    return result


def zip_members(blob: bytes, budget: Budget) -> dict[str, tuple[bytes, int]]:
    """Reject zip64/multipart/encrypted/symlink wheels and bound central metadata."""
    end = blob.rfind(b'PK\x05\x06', max(0, len(blob) - 65557))
    need(end >= 0 and len(blob) >= end + 22, 'zip_directory_missing')
    disk, start, count_disk, count, size, offset, comment = struct.unpack_from('<4H2IH', blob, end + 4)
    need(disk == start == 0 and count_disk == count and count < 65535 and
         count <= MAX_NODES and size <= 16 * 1024 ** 2 and offset + size == end and
         end + 22 + comment == len(blob), 'unsupported_zip_directory')
    result = {}
    with zipfile.ZipFile(io.BytesIO(blob)) as archive:
        need(len(archive.infolist()) == count, 'zip_directory_count')
        for item in archive.infolist():
            budget.tick(nodes=1)
            name = path_name(item.filename.rstrip('/') if item.is_dir() else item.filename)
            need(name not in result, 'duplicate_archive_path')
            mode = item.external_attr >> 16
            need(stat.S_IFMT(mode) in (0, stat.S_IFREG, stat.S_IFDIR) and
                 not mode & 0o7000 and not item.flag_bits & 1, 'unsupported_zip_member')
            need(item.is_dir() == (stat.S_ISDIR(mode) or item.filename.endswith('/')),
                 'zip_member_type')
            need(0 <= item.file_size <= MAX_FILE, 'archive_member_limit')
            budget.tick(expanded=item.file_size)
            with archive.open(item) as source:
                data = source.read(item.file_size + 1)
            need(len(data) == item.file_size, 'archive_member_size')
            if item.is_dir():
                need(not data, 'archive_directory_content')
                result[name] = b'', stat.S_IFDIR | 0o755
            else:
                result[name] = data, mode or 0o644
    return result


def artifact(files: Files, category: str, descriptor: dict, suffix: str) -> bytes:
    fields(descriptor, {'url', 'sha256', 'size'})
    digest = hash_value(descriptor['sha256'])
    need(type(descriptor['size']) is int and 0 < descriptor['size'] <= MAX_ARTIFACT,
         'artifact_size_limit')
    need(isinstance(descriptor['url'], str) and descriptor['url'].startswith('https://'), 'artifact_url')
    data, record = files.file(category + '/' + digest + suffix, MAX_ARTIFACT)
    need(record['sha256'] == digest and record['size'] == descriptor['size'], 'artifact_hash_mismatch')
    return data


def normalized(name: str) -> str:
    need(isinstance(name, str) and re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._-]{0,100}', name),
         'invalid_distribution_name')
    return re.sub('[-_.]+', '-', name).lower()


def production_packages(lock: dict) -> tuple[dict, set[str]]:
    """Only the markers present in the authenticated pinned Linux lock are supported."""
    markers = {"python_full_version < '3.12'": False, "python_full_version >= '3.12'": True,
               "sys_platform == 'darwin'": False, "sys_platform == 'win32'": False}
    packages = lock['package']
    roots = [p for p in packages if p['name'] == 'outpost-browser-engine']
    need(len(roots) == 1 and roots[0]['source'] == {'virtual': '.'}, 'lock_project_mismatch')
    direct = {normalized(d['name']) for d in roots[0]['dependencies']}
    need(direct == {'camoufox', 'playwright'}, 'lock_direct_dependencies')
    result, pending = {}, list(roots[0]['dependencies'])
    while pending:
        dep = pending.pop()
        if 'marker' in dep:
            need(dep['marker'] in markers, 'unsupported_lock_marker')
            if not markers[dep['marker']]:
                continue
        name = normalized(dep['name'])
        candidates = [p for p in packages if normalized(p['name']) == name and
                      ('version' not in dep or p['version'] == dep['version'])]
        need(len(candidates) == 1, 'ambiguous_lock_dependency')
        package = candidates[0]
        need(package['source'] == {'registry': 'https://pypi.org/simple'}, 'unsupported_lock_source')
        if name in result:
            need(result[name]['version'] == package['version'], 'conflicting_lock_dependency')
            continue
        result[name] = package
        pending.extend(package.get('dependencies', []))
    return result, direct


def compatible_wheel(url: str) -> None:
    filename = url.rsplit('/', 1)[-1]
    need(filename.endswith('.whl'), 'wheel_filename')
    pieces = filename[:-4].split('-')
    need(len(pieces) in (5, 6), 'wheel_filename')
    python, abi, platform = pieces[-3:]
    compatible_python = bool(set(python.split('.')) & {'py3', 'cp313'})
    if abi == 'abi3':
        compatible_python = any(re.fullmatch(r'cp3(?:[2-9]|1[0-3])', p) for p in python.split('.'))
    need(compatible_python and abi in ('none', 'cp313', 'abi3'), 'wheel_python_tag')
    need(any(p == 'any' or p == 'linux_x86_64' or
             re.fullmatch(r'manylinux(?:1|2010|2014|_2_[0-9]+)_x86_64', p)
             for p in platform.split('.')), 'wheel_platform_tag')


def headers(data: bytes) -> dict[str, list[str]]:
    need(len(data) <= MAX_METADATA, 'metadata_size_limit')
    result: dict[str, list[str]] = {}
    for line in data.decode('utf-8').split('\n\n', 1)[0].splitlines():
        if line.startswith((' ', '\t')):
            continue
        key, separator, value = line.partition(':')
        need(separator, 'invalid_metadata_header')
        result.setdefault(key.lower(), []).append(value.strip())
    return result


def wheel_path(name: str, stem: str, distribution: str) -> str:
    """PEP 427 spread, using UV's fixed CPython 3.13 Linux installation scheme."""
    parts = path_name(name).split('/')
    if parts[0].endswith('.data'):
        need(parts[0] == stem + '.data' and len(parts) >= 3, 'wheel_data_path')
        schemes = {'purelib': SITE, 'platlib': SITE, 'scripts': VENV + '/bin',
                   'headers': VENV + '/include/site/python3.13/' + distribution,
                   'data': VENV}
        need(parts[1] in schemes, 'wheel_data_scheme')
        return schemes[parts[1]] + '/' + '/'.join(parts[2:])
    return SITE + '/' + name


