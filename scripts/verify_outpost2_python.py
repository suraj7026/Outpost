def shebang(templates: dict[str, bytes]) -> bytes:
    """Only the fixed, non-relocatable simple POSIX branch is applicable here."""
    need(b'format!("#!{executable}")' in templates[UV_WHEEL] and
         len(VENV_PYTHON.encode()) + 3 <= 127 and ' ' not in VENV_PYTHON,
         'unsupported_shebang_layout')
    return b'#!' + VENV_PYTHON.encode()


def entrypoints(data: bytes, templates: dict[str, bytes]) -> dict[str, bytes]:
    """Read (never import) entry points; render UV's exact Rust raw-string template."""
    parser = configparser.ConfigParser(interpolation=None, strict=True, delimiters=('=',))
    parser.optionxform = lambda optionstr: optionstr
    parser.read_string(data.decode('utf-8'))
    need(not parser.defaults(), 'unsupported_entrypoint_defaults')
    source = templates[UV_WHEEL]
    fragment = source.split(b'fn get_script_launcher(', 1)[1].split(b'/// Part of entrypoints parsing', 1)[0]
    matches = re.findall(rb'r#"(.*?)"#', fragment, re.S)
    need(len(matches) == 1, 'entrypoint_source_template')
    template = matches[0]
    identifier = r'[A-Za-z_][A-Za-z_0-9]*(?:\.[A-Za-z_][A-Za-z_0-9]*)*'
    result = {}
    for group in ('console_scripts', 'gui_scripts'):
        if not parser.has_section(group):
            continue
        for name, value in parser.items(group):
            need(re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._+\-]*', name), 'unsafe_entrypoint_name')
            need(name not in GENERATED_NAMES | {'python', 'pythonw', 'python3'} and
                 not re.fullmatch(r'python3\.[0-9]+', name), 'reserved_entrypoint_name')
            need(not re.fullmatch(r'pip(?:3(?:\.[0-9]+)?)?', name), 'unsupported_pip_entrypoint')
            match = re.fullmatch('(' + identifier + r')\s*:\s*(' + identifier +
                                 r')(?:\s*\[\s*[A-Za-z0-9_.\-, ]+\])?\s*', value)
            if match is None:
                raise Refused('unsupported_entrypoint_value')
            module, function = match[1], match[2]
            replacements = {'shebang': shebang(templates), 'module': module.encode(),
                            'function': function.encode(), 'import_name': function.split('.')[0].encode()}
            rendered = template
            for key, replacement in replacements.items():
                rendered = rendered.replace(('{' + key + '}').encode(), replacement)
            path = VENV + '/bin/' + name
            need(path not in result, 'entrypoint_collision')
            result[path] = rendered
    return result


def rewrite_script(data: bytes, templates: dict[str, bytes]) -> bytes:
    """wheel.rs consumes ONE CR or LF after #!python, preserving a following LF."""
    if not data.startswith(b'#!python'):
        return data
    end = re.search(b'[\r\n]', data[8:])
    rest = data[8 + end.end():] if end else b''
    return shebang(templates) + b'\n' + rest


def record_row(path: str, ref: Reference) -> list[str]:
    digest = base64.urlsafe_b64encode(bytes.fromhex(ref.sha256)).decode().rstrip('=')
    return [posixpath.relpath(path, SITE), 'sha256=' + digest, str(ref.size)]


def wheel_record_rows(members: dict, info: str) -> dict[str, list[str]]:
    """Bound the authenticated wheel RECORD; its assertions never prove payloads."""
    result = {}
    for row in csv.reader(io.StringIO(members[info + '/RECORD'][0].decode(), newline=''), strict=True):
        need(len(row) == 3 and row[0] not in result and row[0] in members and
             not stat.S_ISDIR(members[row[0]][1]), 'reference_record_bounds')
        name, digest, size = row
        path_name(name)
        need((not size or re.fullmatch(r'[0-9]{1,12}', size)) and
             (not digest or re.fullmatch(r'sha(?:256|384|512)=[A-Za-z0-9_\-]+', digest)),
             'reference_record_bounds')
        if size:
            row[2] = str(int(size))
        result[name] = row
    need(set(result) == {n for n, (_, mode) in members.items() if not stat.S_ISDIR(mode)},
         'reference_record_bounds')
    need(result[info + '/RECORD'][1:] == ['', ''], 'reference_record_self_row')
    return result


def wheel_reference(blob: bytes, descriptor: dict, budget: Budget,
                    templates: dict[str, bytes]) -> tuple[dict, str, dict, list[str]]:
    members = zip_members(blob, budget)
    metadata = [n for n in members if n.count('/') == 1 and n.endswith('.dist-info/METADATA')]
    need(len(metadata) == 1, 'wheel_dist_info')
    info = metadata[0].rsplit('/', 1)[0]
    stem = info[:-len('.dist-info')]
    meta = headers(members[info + '/METADATA'][0])
    need(len(meta.get('name', [])) == 1 and len(meta.get('version', [])) == 1 and
         normalized(meta['name'][0]) == normalized(descriptor['name']) and
         meta['version'][0] == descriptor['version'], 'wheel_identity_mismatch')
    need(stem == descriptor['name'].replace('-', '_') + '-' + descriptor['version'] or
         normalized(stem.rsplit('-', 1)[0]) == normalized(descriptor['name']) and
         stem.rsplit('-', 1)[-1] == descriptor['version'], 'wheel_dist_info_name')
    wheel = headers(members[info + '/WHEEL'][0])
    need(wheel.get('wheel-version') == ['1.0'] and wheel.get('root-is-purelib') in
         (['true'], ['false']), 'unsupported_wheel_format')
    for n in members:
        if n.endswith('.dist-info') or '.dist-info/' in n:
            need(n == info or n.startswith(info + '/'), 'multiple_dist_info')
    generated = entrypoints(members[info + '/entry_points.txt'][0], templates) if info + '/entry_points.txt' in members else {}
    need(info + '/RECORD' in members, 'wheel_record_missing')
    rows = wheel_record_rows(members, info)
    tree, payloads, derived = {}, {}, []
    for name, (data, mode) in members.items():
        if stat.S_ISDIR(mode):
            # Structural .data directories are not installed; other empty directories are.
            if not name.split('/')[0].endswith('.data'):
                insert(tree, SITE + '/' + name, Reference('dir'))
            continue
        path = wheel_path(name, stem, normalized(descriptor['name']))
        need(posixpath.basename(path) not in GENERATED_NAMES, 'reserved_wheel_generated_path')
        if name == info + '/RECORD':
            continue
        need(not name.endswith(('/INSTALLER', '/REQUESTED', '/direct_url.json', '/uv_cache.json', '/uv_build.json')),
             'unexpected_wheel_install_metadata')
        rows[name][0] = posixpath.relpath(path, SITE)
        if name.startswith(stem + '.data/scripts/'):
            leaf = name[len(stem + '.data/scripts/'):]
            need('/' not in leaf, 'unsupported_nested_wheel_script')
            match_name = leaf
            for suffix in ('.exe', '-script.py', '.pya'):
                if leaf.endswith(suffix):
                    match_name = leaf[:-len(suffix)]
                    break
            need(VENV + '/bin/' + match_name not in generated, 'unsupported_shadowed_wheel_script')
            rewritten = rewrite_script(data, templates)
            if data.startswith(b'#!python'):
                rows[name] = record_row(path, regular(rewritten))
                derived.append(path)
            data, mode = rewritten, mode | 0o111
        insert(tree, path, regular(data, mode))
        if name == 'camoufox/fpgen-model.json':
            payloads[name] = data
    generated[SITE + '/' + info + '/INSTALLER'] = b'uv'
    generated[SITE + '/' + info + '/REQUESTED'] = b''
    extra_rows = []
    for path, data in generated.items():
        ref = regular(data, 0o755 if path.startswith(VENV + '/bin/') else 0o644)
        insert(tree, path, ref)
        extra_rows.append(record_row(path, ref))
        derived.append(path)
    output = io.StringIO(newline='')
    csv.writer(output, lineterminator='\n').writerows(sorted(list(rows.values()) + extra_rows))
    record_path = SITE + '/' + info + '/RECORD'
    insert(tree, record_path, regular(output.getvalue().encode()))
    derived.append(record_path)
    return tree, SITE + '/' + info, payloads, derived


def patch_sysconfig(data: bytes, templates: dict[str, bytes]) -> bytes:
    """Port only the pinned UV data transformation; never execute the Python file."""
    header = b'# system configuration generated and used by the sysconfig module\n'
    need(data.startswith(header) and len(data) <= MAX_METADATA, 'unsupported_sysconfig_format')
    parsed = ast.parse(data.decode())
    need(len(parsed.body) == 1 and isinstance(parsed.body[0], ast.Assign), 'unsupported_sysconfig_format')
    assignment = parsed.body[0]
    if not isinstance(assignment, ast.Assign):
        raise Refused('unsupported_sysconfig_format')
    need(len(assignment.targets) == 1 and isinstance(assignment.targets[0], ast.Name) and
         assignment.targets[0].id == 'build_time_vars' and isinstance(assignment.value, ast.Dict),
         'unsupported_sysconfig_format')
    values = ast.literal_eval(assignment.value)
    need(type(values) is dict and len(values) <= 4096 and
         all(type(k) is str and k.isascii() and (type(x) is int and -(2**31) <= x < 2**31 or
             type(x) is str and x.isascii()) for k, x in values.items()), 'unsupported_sysconfig_values')
    # The original PBS file uses JSON string escapes compatible with the pinned
    # parser. Reject other Python escape semantics rather than approximate them.
    need(all(m[1] in (b'\\', b"'", b'"') for m in re.finditer(rb'\\(.)', data, re.S)),
         'unsupported_sysconfig_escape')
    mappings = templates[UV_SYSCONFIG + 'generated_mappings.rs'].decode()
    groups = re.findall(r'\("([A-Z]+)"\.to_string\(\), vec!\[(.*?)\]\)', mappings, re.S)
    need({key for key, _ in groups} == {'BLDSHARED', 'CC', 'CXX', 'LDCXXSHARED', 'LDSHARED', 'LINKCC', 'AR'},
         'unsupported_sysconfig_mapping')
    rules = {}
    for key, body in groups:
        partial = re.findall(r'ReplacementEntry \{ mode: ReplacementMode::Partial \{ from: "([^"]+)"\.to_string\(\) \}, to: "([^"]+)"\.to_string\(\) \}', body)
        if key == 'AR':
            need('ReplacementMode::Full' in body and 'to: "ar".to_string()' in body, 'unsupported_sysconfig_mapping')
            rules[key] = [(None, 'ar')]
        else:
            need(len(partial) == body.count('ReplacementEntry'), 'unsupported_sysconfig_mapping')
            rules[key] = partial
    prefix = '/' + RELEASE + '/' + PRIVATE
    for key, value in values.items():
        if type(value) is not str:
            continue
        words = []
        parts = iter(value.split())
        for word in parts:
            if word.startswith('/install'):
                rest = word[len('/install'):]
                need(not rest or rest.startswith('/') and '..' not in rest.split('/'), 'unsupported_sysconfig_prefix')
                word = prefix + rest
            if word == '-isysroot':
                next(parts, None)
            else:
                words.append(word)
        patched = ' '.join(words)
        for before, after in rules.get(key, []):
            patched = after if before is None else ' '.join(after if w == before else w for w in patched.split())
        values[key] = patched
    values['PYTHON_BUILD_STANDALONE'] = 1
    return header + b'build_time_vars = ' + json.dumps(values, sort_keys=True, ensure_ascii=False, indent=4).encode() + b'\n'


def patch_pkgconfig(data: bytes) -> bytes:
    """sysconfig/mod.rs patch_pkgconfig: changed output has no final newline."""
    lines, changed = [], False
    for line in data.decode().splitlines():
        key, sep, value = line.partition('=')
        if sep and all(c.isascii() and c.isalpha() for c in key) and value == '/install':
            line, changed = key + '=${pcfiledir}/../..', True
        lines.append(line)
    return '\n'.join(lines).encode() if changed else data


def python_reference(blob: bytes, budget: Budget, templates: dict[str, bytes],
                     python_pin: dict) -> tuple[dict[str, Reference], list[str]]:
    tree = {}
    members = tar_members(blob, budget)
    sysconfigs = [n for n, (item, _) in members.items() if item.isfile() and
                  re.fullmatch(r'python/lib/python3\.13/_sysconfigdata_[^/]+\.py', n)]
    need(len(sysconfigs) == 1, 'unsupported_sysconfig_path_count')
    derived = []
    for name, (item, data) in members.items():
        need(name == 'python' or name.startswith('python/'), 'python_archive_prefix')
        path = PRIVATE + name[len('python'):]
        if item.isfile():
            if name == sysconfigs[0]:
                data = patch_sysconfig(data, templates)
                derived.append(path)
            elif name.startswith('python/lib/pkgconfig/') and name.endswith('.pc'):
                patched = patch_pkgconfig(data)
                if patched != data:
                    derived.append(path)
                data = patched
            ref = regular(data, item.mode)
        elif item.isdir():
            ref = Reference('dir')
        elif item.issym():
            ref = Reference('link', target=item.linkname)
        else:
            target = item.linkname.removeprefix('./')
            need(target.startswith('python/') and target in members and members[target][0].isfile(),
                 'unsupported_tar_hardlink')
            ref = regular(members[target][1], members[target][0].mode)
        insert(tree, path, ref)
    need(tree.get(PRIVATE + '/bin/python3.13', Reference('missing')).kind == 'file',
         'python_interpreter_missing')
    managed = templates['crates/uv-python/src/managed.rs']
    marker = re.search(rb'static EXTERNALLY_MANAGED: &str = "([^"]+)";', managed)
    need(marker is not None, 'managed_marker_template')
    if marker is None:
        raise Refused('managed_marker_template')
    need(re.fullmatch(r'[0-9]{8}', python_pin['build']), 'managed_build_metadata')
    additions = {PRIVATE + '/lib/python3.13/EXTERNALLY-MANAGED': marker[1],
                 PRIVATE + '/BUILD': python_pin['build'].encode(), 'python/.gitignore': b'*'}
    for path, data in additions.items():
        insert(tree, path, regular(data))
        derived.append(path)
    insert(tree, 'python/.temp', Reference('dir'))
    insert(tree, MINOR_LINK, Reference('link', target='/' + RELEASE + '/' + PRIVATE))
    return tree, derived


