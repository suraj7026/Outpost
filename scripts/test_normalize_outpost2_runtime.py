    def state(self) -> dict:
        """Full fixture metadata/content excluding read-induced atime changes."""
        result = {}
        for base, dirs, files in os.walk(self.root, followlinks=False):
            path = Path(base)
            label = path.relative_to(self.root).as_posix()
            result[label] = snapshot(path, label)
            for leaf in dirs + files:
                child = path / leaf
                name = child.relative_to(self.root).as_posix()
                info = child.lstat()
                if stat.S_ISLNK(info.st_mode):
                    result[name] = (snapshot(child, name), os.readlink(child))
                elif stat.S_ISREG(info.st_mode):
                    result[name] = (snapshot(child, name), child.read_bytes())
                elif not stat.S_ISDIR(info.st_mode):
                    result[name] = (snapshot(child, name), 'special')
        return result

