    def test_never_write_chmod_chown_or_utime_an_original_inode(self):
        originals = {(p.stat().st_dev, p.stat().st_ino) for p in [self.cache] +
                     [self.release / name for name in self.references | self.quarantine]}
        real = {name: getattr(n.os, name) for name in ('write', 'fchmod', 'fchown', 'utime')}

        def guarded(name):
            def call(fd, *args, **kwargs):
                self.assertIsInstance(fd, int)
                info = os.fstat(fd)
                self.assertNotIn((info.st_dev, info.st_ino), originals)
                return real[name](fd, *args, **kwargs)
            return call

        with ExitStack() as stack:
            for name in real:
                stack.enter_context(patch.object(n.os, name, side_effect=guarded(name)))
            stack.enter_context(patch.object(n.os, 'chmod', side_effect=AssertionError('no path chmod')))
            stack.enter_context(patch.object(n.os, 'chown', side_effect=AssertionError('no path chown')))
            stack.enter_context(patch.object(n.os, 'link', side_effect=AssertionError('no hardlinks')))
            self.normalize()

