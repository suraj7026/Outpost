    def fake_device(self, inode: int):
        """Simulate a mount boundary consistently in lstat and fstat, no mount needed."""
        real_stat, real_fstat = os.stat, os.fstat

        def convert(info):
            if info.st_ino != inode:
                return info
            values = {key: getattr(info, key) for key in dir(info) if key.startswith('st_')}
            values['st_dev'] += 100
            return SimpleNamespace(**values)

        self.stack.enter_context(patch.object(n.os, 'stat', side_effect=lambda *a, **k: convert(real_stat(*a, **k))))
        self.stack.enter_context(patch.object(n.os, 'fstat', side_effect=lambda *a, **k: convert(real_fstat(*a, **k))))

