def digest(data: bytes) -> str:
    """Independent fixture hash implementation."""
    return hashlib.sha256(data).hexdigest()


def snapshot(path: Path, label: str) -> dict:
    """Reproduce the verifier's documented lossless STAT contract."""
    info = path.lstat()
    return {'path': label, 'device': info.st_dev, 'inode': info.st_ino, 'uid': info.st_uid,
            'gid': info.st_gid, 'mode': stat.S_IMODE(info.st_mode), 'nlink': info.st_nlink,
            'size': info.st_size, 'mtimeNs': info.st_mtime_ns, 'ctimeNs': info.st_ctime_ns}


