"""One-operation, stdlib-only runtime normalization. NO CLI and NO execution.

Production API: normalize(release: Path, audit: Path, proof: dict) -> dict.
Only /opt/outpost-native/releases/host-fa9eb6b5d217af95b920 and a pre-existing
root:root 0700 OP/continuation-<canonical UUID> audit are accepted. The explicit
normalize_for_test(root, release, audit, proof) seam remaps those SAME paths;
production never obtains a root, path, owner, or trust override from a CLI/env.

The pinned, authenticated wrapper must hold the ORIGINAL install lock, exclude
all writers (including service UIDs, cache writers and audit log writers), and
retain that exclusion through re-verification/sealing. Stat checks are optimistic,
not protection against hostile root/mount races. Run trusted system Python -I -B.
This module does not authenticate its own caller, acquire locks, load proofs from
disk, run verifiers, interpret installed code, or authorize services.

Proof schema (exact keys; integers must remain lossless):
  schemaVersion: 1, operationId: OPERATION_ID, releaseId: RELEASE_ID,
  buildUid: int, buildGid: int,
  verifiedFiles: [STAT + {sha256}],
  verifiedLinks: [STAT + {sha256, target}],
  quarantineBytecode: [STAT + {sha256}],
  quarantineDirectories: [release-relative path],
  assertions: {root: str, releasePath: RELEASE,
               ancestors: [STAT], ownedDirectories: [STAT]}.
STAT is {path, device, inode, uid, gid, mode, nlink, size, mtimeNs, ctimeNs}.
File/link/directory paths are release-relative; ancestors are root-relative,
with '.' for root. ancestors is EXACTLY the parent closure of the five TREES.
ownedDirectories is the complete runtime directory inventory, including the
roots and generated __pycache__ directories. No summaries are authorization.

The wrapper assembles this object INTERNALLY from successful pinned verifiers:
Python supplies full STAT records/assertions. Node supplies hashes, sizes, modes,
nlink and exact link targets but NOT full snapshots or directory assertions;
the wrapper must capture those no-follow, verify Node over the SAME unchanged
namespace, and recheck its snapshots before constructing this union. Merely
hashing installed files is NOT proof. Source/assets/static-code authentication,
account identity and the pinned verifier/helper bytes remain wrapper gates.
The wrapper includes quarantineDirectories ONLY for generated cache directories
absent from authenticated archive/template references. They must contain only
enumerated source-backed quarantine files; mixed/authenticated directories stay.
All other static release paths are inspected for structural safety/aliasing but
are neither content-authenticated here nor accepted as quarantine sources.

Before the first write: validate the entire proof, all hashes/stat snapshots,
full runtime namespace, link destinations, ownership/modes, audit/ancestors,
alias uniqueness, same-device destinations, resource limits and stop markers.
Multiple internal aliases (even outside runtime scopes) and nlink > 2 refuse.
No cache pathname is opened. Backups are new independent root:root 0600 files,
fsynced before any replacement/unlink. Only verified nlink=2 files are replaced,
via an audit-staged byte-identical inode preserving uid/gid/mode AND mtime.
Empty proved Python locks may be 0666; they are never chmod/chowned/sealed here.
Untrusted generated pycs are backed up then exact-inode unlinked, never executed.
Explicit generated directories are removed only after their backed-up children
are gone and an exact empty-directory recheck. Archive-authenticated pycs remain.

The audit/runtime-normalization directory is a permanent stop marker, even if
empty or complete. Any exception after its creation requires manual review;
there is NO automatic cleanup, rollback, retry or resume. intent.json, proof.json,
per-file backup receipts, evidence.json, per-action applied receipts and finally
applied.json record the boundary (a crash can precede its applied receipt).
Per-action files are sharded into private items-NNNN directories (64 actions
per directory), avoiding quadratic audit enumeration at the real 2,436-file scale.
Directory size/nlink/mtime/ctime changes are adopted ONLY immediately after our
own exact namespace delta, preserving identity/owner/mode, then guarded exactly
again. Guards are not disabled after our first write. All output is bounded.
Success still requires fresh pinned verifications, zero generated bytecode and
hardlinks, and the parent's explicit sealing/activation gates. executionAuthorized
is always false. No permission/owner change ever targets an original inode.
"""
from __future__ import annotations

import hashlib
import json
import os
import posixpath
import re
import stat
import time
import uuid
from contextlib import contextmanager
from pathlib import Path

OPERATION_ID = '645f62a9-37c8-413e-b31e-9372bc2ed774'
RELEASE_ID = 'host-fa9eb6b5d217af95b920'
OP = 'var/lib/outpost-setup/operations/' + OPERATION_ID
RELEASE = 'opt/outpost-native/releases/' + RELEASE_ID
VENV = 'server/browser-engine/.venv'
TREES = ('node', 'node_modules', 'browsers', 'python', VENV)
LOCKS = {'python/.lock', VENV + '/.lock'}
MARKER = 'runtime-normalization'
ROOT_UID = ROOT_GID = 0  # Tests may patch these; never populated from proof/env.
MAX_NODES = 100000
MAX_ACTIONS = 10000
MAX_FILE = 6 * 1024 ** 3
MAX_BYTES = 32 * 1024 ** 3
MAX_BACKUP_BYTES = 2 * 1024 ** 3
MAX_JSON = 64 * 1024 ** 2
MAX_SECONDS = 600
CHUNK = 1024 * 1024
GROUP_SIZE = 64
STAT = {'path', 'device', 'inode', 'uid', 'gid', 'mode', 'nlink', 'size', 'mtimeNs', 'ctimeNs'}
STABLE_DIRECTORY = ('device', 'inode', 'uid', 'gid', 'mode')
DIRECTORY_FLAGS = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC
READ_FLAGS = os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC | getattr(os, 'O_NOATIME', 0)


class Refused(RuntimeError):
    """Fixed reason code; a retained marker always requires manual review."""


def need(condition: object, reason: str) -> None:
    """Reject without exposing arbitrary filesystem/OS text."""
    if not condition:
        raise Refused(reason)


def sha(data: bytes) -> str:
    """SHA-256 for evidence, not independent provenance."""
    return hashlib.sha256(data).hexdigest()


def record(path: str, info: os.stat_result) -> dict:
    """Verifier-compatible snapshot; atime is deliberately not a precondition."""
    return {'path': path, 'device': info.st_dev, 'inode': info.st_ino, 'uid': info.st_uid,
            'gid': info.st_gid, 'mode': stat.S_IMODE(info.st_mode), 'nlink': info.st_nlink,
            'size': info.st_size, 'mtimeNs': info.st_mtime_ns, 'ctimeNs': info.st_ctime_ns}


def fields(value: object, keys: set[str]) -> dict:
    """Require an exact, plain dictionary, not executable/custom mapping behavior."""
    if type(value) is not dict or value.keys() != keys:
        raise Refused('proof_shape')
    return value


def path_name(value: object, *, dot: bool = False) -> str:
    """Reject aliases/escapes rather than normalizing untrusted path spellings."""
    if type(value) is not str or not 0 < len(value) <= 1024:
        raise Refused('unsafe_path')
    if dot and value == '.':
        return value
    need(all(32 <= ord(c) < 127 and c not in '\\:' for c in value), 'unsafe_path')
    parts = value.split('/')
    need(len(parts) <= 64 and all(p not in ('', '.', '..') and len(p) <= 255 for p in parts), 'unsafe_path')
    return value


def runtime(path: str) -> bool:
    """Restrict mutation authority to the five reviewed runtime trees."""
    return any(path == tree or path.startswith(tree + '/') for tree in TREES)


def ancestors() -> set[str]:
    """The exact root-relative lookup context supplied by the Python verifier."""
    result = {'.'}
    for tree in TREES:
        name = posixpath.dirname(RELEASE + '/' + tree)
        while name:
            result.add(name)
            name = posixpath.dirname(name)
    return result


def encoded(value: dict) -> bytes:
    """Bounded, deterministic, non-executable evidence."""
    data = (json.dumps(value, sort_keys=True, separators=(',', ':'), allow_nan=False) + '\n').encode()
    need(len(data) <= MAX_JSON, 'json_limit')
    return data


class Budget:
    """Bound aggregate reads/writes, nodes and elapsed time, including rechecks."""

    def __init__(self) -> None:
        self.deadline = time.monotonic() + MAX_SECONDS
        self.bytes = 0

    def tick(self, size: int = 0) -> None:
        self.bytes += size
        need(self.bytes <= MAX_BYTES, 'byte_limit')
        need(time.monotonic() <= self.deadline, 'time_limit')


def validate_proof(proof: dict, root: Path) -> dict:
    """Validate and copy every field before any filesystem write."""
    keys = {'schemaVersion', 'operationId', 'releaseId', 'buildUid', 'buildGid',
            'verifiedFiles', 'verifiedLinks', 'quarantineBytecode', 'quarantineDirectories', 'assertions'}
    fields(proof, keys)
    need(type(proof['schemaVersion']) is int and proof['schemaVersion'] == 1 and
         type(proof['operationId']) is str and type(proof['releaseId']) is str and
         proof['operationId'] == OPERATION_ID and proof['releaseId'] == RELEASE_ID, 'proof_identity')
    for key in ('buildUid', 'buildGid'):
        need(type(proof[key]) is int and 0 < proof[key] < 2 ** 32 - 1, 'proof_owner')
    assertions = fields(proof['assertions'], {'root', 'releasePath', 'ancestors', 'ownedDirectories'})
    need(type(assertions['root']) is str and assertions['root'] == str(root) and
         assertions['releasePath'] == RELEASE, 'proof_root')
    result: dict = {key: proof[key] for key in ('schemaVersion', 'operationId', 'releaseId', 'buildUid', 'buildGid')}
    result['assertions'] = {'root': str(root), 'releasePath': RELEASE}
    count, names = 0, set()
    inventories: dict[str, list[dict]] = {}
    for key in ('verifiedFiles', 'verifiedLinks', 'quarantineBytecode', 'ancestors', 'ownedDirectories'):
        source = assertions if key in ('ancestors', 'ownedDirectories') else proof
        target: dict = result['assertions'] if source is assertions else result
        rows = source[key]
        if type(rows) is not list or len(rows) > MAX_NODES:
            raise Refused('proof_limit')
        records: list[dict] = []
        target[key] = records
        inventories[key] = records
        for raw in rows:
            count += 1
            need(count <= MAX_NODES, 'proof_limit')
            extra = {'sha256', 'target'} if key == 'verifiedLinks' else {'sha256'} if key in (
                'verifiedFiles', 'quarantineBytecode') else set()
            row = fields(raw, STAT | extra)
            path = path_name(row['path'], dot=key == 'ancestors')
            name = path if key == 'ancestors' else RELEASE + '/' + path
            need(name not in names, 'duplicate_path')
            names.add(name)
            need(key == 'ancestors' or runtime(path), 'outside_runtime')
            for field in STAT - {'path'}:
                need(type(row[field]) is int and 0 <= row[field] < 2 ** 64, 'invalid_stat')
            need(row['inode'] > 0 and row['nlink'] > 0 and row['mode'] <= 0o7777 and
                 row['uid'] < 2 ** 32 - 1 and row['gid'] < 2 ** 32 - 1, 'invalid_stat')
            if extra:
                need(row['size'] <= MAX_FILE and type(row['sha256']) is str and
                     re.fullmatch('[0-9a-f]{64}', row['sha256']), 'invalid_hash_or_size')
            if key == 'verifiedLinks':
                target_text = row['target']
                need(type(target_text) is str and 0 < len(target_text) <= 1024 and
                     all(32 <= ord(c) < 127 and c not in '\\:' for c in target_text), 'unsafe_link')
                need(row['sha256'] == sha(os.fsencode(target_text)), 'link_digest')
            records.append(dict(row))
    need({r['path'] for r in inventories['ancestors']} == ancestors(), 'ancestor_coverage')
    directories = {r['path'] for r in inventories['ownedDirectories']}
    need(set(TREES) <= directories, 'directory_coverage')
    all_paths = {r['path'] for key in ('verifiedFiles', 'verifiedLinks', 'quarantineBytecode') for r in result[key]} | directories
    for name in all_paths:
        parent = posixpath.dirname(name)
        need(parent in directories or (RELEASE + '/' + parent if parent else RELEASE) in ancestors(), 'directory_coverage')
    sources = {r['path'] for r in result['verifiedFiles'] if r['path'].endswith('.py')}
    for row in result['quarantineBytecode']:
        match = re.fullmatch(r'(.+)/__pycache__/([^/]+)\.cpython-313(?:\.opt-[12])?\.pyc', row['path'])
        need((row['path'].startswith('python/') or row['path'].startswith(VENV + '/')) and
             match is not None and match[1] + '/' + match[2] + '.py' in sources, 'unauthenticated_bytecode_source')
    qdirs = proof['quarantineDirectories']
    need(type(qdirs) is list and len(qdirs) <= MAX_ACTIONS, 'proof_limit')
    qdirs = [path_name(p) for p in qdirs]
    need(len(qdirs) == len(set(qdirs)), 'duplicate_path')
    quarantined = {r['path'] for r in result['quarantineBytecode']}
    for name in qdirs:
        children = {p for p in all_paths if posixpath.dirname(p) == name}
        need(name in directories and name.endswith('/__pycache__') and children and children <= quarantined,
             'unsafe_quarantine_directory')
    result['quarantineDirectories'] = qdirs
    actions = [r for r in result['verifiedFiles'] if r['nlink'] > 1] + result['quarantineBytecode']
    need(len(actions) + len(qdirs) <= MAX_ACTIONS and sum(r['size'] for r in actions) <= MAX_BACKUP_BYTES, 'action_limit')
    # Includes preflight/final hashing, backup copies, stage verification and receipts.
    need(sum(r['size'] for r in result['verifiedFiles'] + result['quarantineBytecode']) * 3 +
         sum(r['size'] for r in actions) * 20 + MAX_JSON * 3 <= MAX_BYTES, 'byte_limit')
    encoded(result)
    return result


class Guard:
    """No-follow namespace snapshots, with explicit accounting for our own writes."""

    def __init__(self, root: Path, proof: dict, budget: Budget) -> None:
        self.root, self.proof, self.budget = root, proof, budget
        self.dirs: dict[str, dict] = {}
        self.leaves: dict[str, tuple[int, dict]] = {}
        self.listings: dict[str, set[str]] = {}
        self.chain: list[dict] = []
        self.fd, self.chain = self.anchor()
        self.dirs['.'] = record('.', os.fstat(self.fd))

    def anchor(self) -> tuple[int, list[dict]]:
        """Open the explicit root without resolving any ancestor symlink."""
        fd, chain = os.open('/', DIRECTORY_FLAGS), []
        try:
            for part in self.root.parts[1:]:
                before = os.stat(part, dir_fd=fd, follow_symlinks=False)
                need(stat.S_ISDIR(before.st_mode), 'symlink_ancestor')
                child = os.open(part, DIRECTORY_FLAGS, dir_fd=fd)
                try:
                    need(record(part, before) == record(part, os.fstat(child)), 'namespace_changed')
                except BaseException:
                    os.close(child)
                    raise
                os.close(fd)
                fd = child
                chain.append(record(part, before))
            return fd, chain
        except BaseException:
            os.close(fd)
            raise

    def close(self) -> None:
        """Never remove partial evidence or attempt rollback."""
        os.close(self.fd)

    def metadata(self, name: str, info: os.stat_result, *, private: bool = False) -> None:
        """Validate owners/modes independently of self-reported snapshots."""
        mode = stat.S_IMODE(info.st_mode)
        pair = (info.st_uid, info.st_gid)
        build = (self.proof['buildUid'], self.proof['buildGid'])
        inside = name == RELEASE or name.startswith(RELEASE + '/')
        need(pair in ({(ROOT_UID, ROOT_GID), build} if inside else {(ROOT_UID, ROOT_GID)}), 'unsafe_owner')
        if private:
            need((stat.S_ISDIR(info.st_mode) and mode == 0o700) or
                 (stat.S_ISREG(info.st_mode) and mode == 0o600 and info.st_nlink == 1), 'unsafe_audit')
        elif stat.S_ISLNK(info.st_mode):
            # Symlink permission bits differ on macOS; the exact verifier snapshot
            # and target are checked separately, and the link is never followed.
            need(info.st_nlink == 1 and not mode & 0o7000, 'unsafe_link')
        else:
            lock = name in {RELEASE + '/' + p for p in LOCKS}
            need(stat.S_ISDIR(info.st_mode) or stat.S_ISREG(info.st_mode), 'special_file')
            need(not mode & 0o7000 and (not mode & 0o022 or
                 lock and stat.S_ISREG(info.st_mode) and info.st_size == 0 and mode == 0o666 and info.st_nlink == 1), 'unsafe_mode')

    @contextmanager
    def directory(self, name: str):
        """Reopen and compare every component, not just a cached descriptor."""
        path_name(name, dot=True)
        fd, current = os.dup(self.fd), ''
        try:
            need(record('.', os.fstat(fd)) == self.dirs['.'], 'namespace_changed')
            for part in name.split('/') if name != '.' else ():
                current = current + '/' + part if current else part
                self.budget.tick()
                before = os.stat(part, dir_fd=fd, follow_symlinks=False)
                need(stat.S_ISDIR(before.st_mode), 'symlink_ancestor')
                self.metadata(current, before)
                snap = record(current, before)
                need(self.dirs.get(current, snap) == snap, 'namespace_changed')
                child = os.open(part, DIRECTORY_FLAGS, dir_fd=fd)
                try:
                    need(record(current, os.fstat(child)) == snap, 'namespace_changed')
                except BaseException:
                    os.close(child)
                    raise
                os.close(fd)
                fd = child
                self.dirs[current] = snap
            yield fd
        finally:
            os.close(fd)

    def names(self, fd: int) -> set[str]:
        """Bound directory enumeration without following children or touching atime on Linux."""
        scan = os.open('.', DIRECTORY_FLAGS | getattr(os, 'O_NOATIME', 0), dir_fd=fd)
        try:
            result = set()
            with os.scandir(scan) as entries:
                for item in entries:
                    self.budget.tick()
                    need(len(result) < MAX_NODES, 'node_limit')
                    result.add(path_name(item.name))
            return result
        finally:
            os.close(scan)

    def check_listing(self, name: str, fd: int) -> None:
        """Compare a previously recorded full child set and directory snapshot."""
        need(record(name, os.fstat(fd)) == self.dirs[name] and
             self.names(fd) == self.listings[name], 'namespace_changed')

    def changed(self, name: str, fd: int, *, added: set[str], removed: set[str]) -> dict:
        """Adopt only our immediately observed exact namespace delta; retain all guards."""
        before = self.dirs[name]
        after = record(name, os.fstat(fd))
        need(not (added & self.listings[name]) and removed <= self.listings[name], 'namespace_collision')
        expected = (self.listings[name] - removed) | added
        need(all(before[k] == after[k] for k in STABLE_DIRECTORY) and self.names(fd) == expected,
             'namespace_changed')
        # Directory nlink conventions differ on APFS/Linux. Only one-entry effects
        # occur here; size/timestamps are filesystem-assigned, never guessed/reset.
        need(abs(after['nlink'] - before['nlink']) <= len(added) + len(removed), 'namespace_changed')
        self.dirs[name], self.listings[name] = after, expected
        return {'before': before, 'after': after}

    def scan(self, name: str, *, private: bool = False) -> None:
        """Snapshot a complete tree, never traverse a link or a mounted child."""
        with self.directory(name) as fd:
            start = record(name, os.fstat(fd))
            self.metadata(name, os.fstat(fd), private=private)
            self.listings[name] = self.names(fd)
            children = []
            for leaf in sorted(self.listings[name]):
                path = name + '/' + leaf
                path_name(path)
                info = os.stat(leaf, dir_fd=fd, follow_symlinks=False)
                need(info.st_dev == start['device'], 'cross_device')
                self.metadata(path, info, private=private)
                if stat.S_ISDIR(info.st_mode):
                    children.append(path)
                else:
                    self.leaves[path] = (stat.S_IFMT(info.st_mode), record(path, info))
                need(len(self.dirs) + len(self.leaves) + len(children) <= MAX_NODES, 'node_limit')
            for child in children:
                self.scan(child, private=private)
            need(record(name, os.fstat(fd)) == start, 'namespace_changed')

    def info(self, name: str) -> os.stat_result:
        """lstat relative to reopened, guarded parents."""
        parent, leaf = posixpath.split(name)
        with self.directory(parent or '.') as fd:
            return os.stat(leaf, dir_fd=fd, follow_symlinks=False)

    def recheck(self) -> None:
        """Check the complete retained namespace, including unmodified static paths."""
        fd, chain = self.anchor()
        try:
            need(chain == self.chain and record('.', os.fstat(fd)) == self.dirs['.'], 'namespace_changed')
        finally:
            os.close(fd)
        for name in list(self.dirs):
            with self.directory(name) as fd:
                if name in self.listings:
                    self.check_listing(name, fd)
        for name, (kind, expected) in self.leaves.items():
            info = self.info(name)
            need(stat.S_IFMT(info.st_mode) == kind and record(name, info) == expected, 'snapshot_changed')

    @contextmanager
    def regular(self, name: str, expected: dict):
        """Bind an exact original inode for copying/rechecking and post-unlink checks."""
        parent, leaf = posixpath.split(name)
        with self.directory(parent) as directory:
            info = os.stat(leaf, dir_fd=directory, follow_symlinks=False)
            need(stat.S_ISREG(info.st_mode) and record(expected['path'], info) ==
                 {k: expected[k] for k in STAT}, 'snapshot_changed')
            fd = os.open(leaf, READ_FLAGS, dir_fd=directory)
            try:
                need(record(expected['path'], os.fstat(fd)) == {k: expected[k] for k in STAT}, 'snapshot_changed')
                yield fd, directory, leaf, info
            finally:
                os.close(fd)

    def hash_fd(self, fd: int, size: int, output: int | None = None) -> str:
        """Stream bounded bytes; never write to the source descriptor."""
        os.lseek(fd, 0, os.SEEK_SET)
        digest, total = hashlib.sha256(), 0
        while True:
            self.budget.tick()
            chunk = os.read(fd, min(CHUNK, size - total + 1))
            if not chunk:
                break
            total += len(chunk)
            need(total <= size, 'size_changed')
            self.budget.tick(len(chunk))
            digest.update(chunk)
            if output is not None:
                self.write_all(output, chunk)
        need(total == size, 'size_changed')
        return digest.hexdigest()

    def write_all(self, fd: int, data: bytes) -> None:
        """Handle short writes, rejecting zero progress."""
        offset = 0
        while offset < len(data):
            written = os.write(fd, data[offset:])
            need(written > 0, 'short_write')
            self.budget.tick(written)
            offset += written

    def verify_file(self, name: str, expected: dict) -> None:
        """Recheck complete bytes and both descriptor/named snapshots."""
        with self.regular(name, expected) as (fd, parent, leaf, _):
            need(self.hash_fd(fd, expected['size']) == expected['sha256'], 'hash_changed')
            want = {k: expected[k] for k in STAT}
            need(record(expected['path'], os.fstat(fd)) == want == record(
                expected['path'], os.stat(leaf, dir_fd=parent, follow_symlinks=False)), 'snapshot_changed')

    def create(self, name: str, *, data: bytes | None = None, source: int | None = None,
               original: dict | None = None, stage: bool = False, atime: int = 0) -> dict:
        """Create ONLY new independent audit files, never truncate or hardlink."""
        parent, leaf = posixpath.split(name)
        with self.directory(parent) as directory:
            self.check_listing(parent, directory)
            need(leaf not in self.listings[parent], 'namespace_collision')
            fd = os.open(leaf, os.O_RDWR | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, 0o600, dir_fd=directory)
            try:
                info = os.fstat(fd)
                need(stat.S_ISREG(info.st_mode) and info.st_nlink == 1 and
                     info.st_dev == self.dirs[parent]['device'], 'unsafe_new_file')
                if source is not None and original is not None:
                    digest = self.hash_fd(source, original['size'], fd)
                    need(digest == original['sha256'], 'hash_changed')
                    size = original['size']
                else:
                    if type(data) is not bytes or len(data) > MAX_JSON:
                        raise Refused('invalid_evidence')
                    self.write_all(fd, data)
                    digest, size = sha(data), len(data)
                uid, gid, mode = (original['uid'], original['gid'], original['mode']) if stage and original else (ROOT_UID, ROOT_GID, 0o600)
                if (info.st_uid, info.st_gid) != (uid, gid):
                    os.fchown(fd, uid, gid)
                os.fchmod(fd, mode)
                if stage and original:
                    os.utime(fd, ns=(atime, original['mtimeNs']))
                os.fsync(fd)
                need(self.hash_fd(fd, size) == digest, 'backup_hash_changed')
                snap = record(name, os.fstat(fd))
                need((snap['uid'], snap['gid'], snap['mode'], snap['nlink']) == (uid, gid, mode, 1) and
                     snap == record(name, os.stat(leaf, dir_fd=directory, follow_symlinks=False)), 'unsafe_new_file')
                self.leaves[name] = (stat.S_IFREG, snap)
                self.changed(parent, directory, added={leaf}, removed=set())
                os.fsync(directory)
                return dict(snap, sha256=digest)
            finally:
                os.close(fd)

    def json(self, name: str, value: dict) -> dict:
        """Exclusively create a durable private journal record."""
        return self.create(name, data=encoded(value))


def validate_links(proof: dict) -> None:
    """Resolve only the authenticated namespace with kernel-order link semantics."""
    kinds = {r['path']: 'file' for r in proof['verifiedFiles']}
    kinds.update({r['path']: 'directory' for r in proof['assertions']['ownedDirectories']})
    kinds.update({'server': 'directory', 'server/browser-engine': 'directory'})
    links = {r['path']: r['target'] for r in proof['verifiedLinks']}
    kinds.update({p: 'link' for p in links})
    for path in links:
        pending, resolved, traversals = path.split('/'), [], 0
        while pending:
            component = pending.pop(0)
            if component == '.':
                continue
            if component == '..':
                need(bool(resolved), 'link_escape')
                resolved.pop()
                continue
            need(component != '', 'unsafe_link')
            resolved.append(component)
            current = '/'.join(resolved)
            need(current in kinds, 'link_target_missing')
            if current in links:
                traversals += 1
                need(traversals <= 64, 'link_cycle')
                target = links[current]
                resolved.pop()
                if target.startswith('/'):
                    need(target.startswith('/' + RELEASE + '/'), 'link_escape')
                    target, resolved = target[len(RELEASE) + 2:], []
                pending = target.split('/') + pending
            elif pending:
                need(kinds[current] == 'directory', 'link_parent_not_directory')
        need(bool(resolved) and runtime('/'.join(resolved)), 'link_escape')


def preflight(guard: Guard, audit: str) -> None:
    """Check independent filesystem facts and EVERY asserted snapshot/hash."""
    proof = guard.proof
    for row in proof['assertions']['ancestors']:
        with guard.directory(row['path']) as fd:
            need(record(row['path'], os.fstat(fd)) == row, 'snapshot_changed')
            guard.metadata(row['path'], os.fstat(fd))
    guard.scan(RELEASE)
    with guard.directory(audit) as fd:
        guard.metadata(audit, os.fstat(fd), private=True)
        need(os.fstat(fd).st_dev == guard.dirs[RELEASE]['device'], 'cross_device')
    with guard.directory(OP) as fd:
        names = guard.names(fd)
        need({n for n in names if n.startswith('continuation-')} == {posixpath.basename(audit)}, 'prior_continuation')
        guard.listings[OP] = names
    guard.scan(audit, private=True)
    need(MARKER not in guard.listings[audit], 'normalization_already_attempted')
    expected = {RELEASE + '/' + r['path']: r for key in (
        'verifiedFiles', 'verifiedLinks', 'quarantineBytecode') for r in proof[key]}
    actual = {p for p in guard.leaves if p.startswith(RELEASE + '/') and runtime(p[len(RELEASE) + 1:])}
    need(actual == set(expected), 'runtime_namespace_mismatch')
    directories = {RELEASE + '/' + r['path']: r for r in proof['assertions']['ownedDirectories']}
    actual_dirs = {p for p in guard.dirs if p.startswith(RELEASE + '/') and runtime(p[len(RELEASE) + 1:])}
    need(actual_dirs == set(directories), 'directory_coverage')
    for name, row in directories.items():
        need(dict(guard.dirs[name], path=row['path']) == row, 'snapshot_changed')
    aliases = set()
    for name, (kind, row) in guard.leaves.items():
        if not name.startswith(RELEASE + '/'):
            continue
        key = row['device'], row['inode']
        need(key not in aliases, 'internal_alias')
        aliases.add(key)
        need(row['nlink'] <= 2, 'unaccounted_aliases')
        need(kind != stat.S_IFLNK or name in expected, 'unproved_link')
        need(row['nlink'] == 1 or name in expected, 'unproved_hardlink')
    for key in ('verifiedFiles', 'quarantineBytecode'):
        for row in proof[key]:
            name = RELEASE + '/' + row['path']
            if key == 'quarantineBytecode':
                need(not row['mode'] & 0o7133, 'unsafe_bytecode_mode')
            if row['path'] in LOCKS:
                need(row['size'] == 0 and row['sha256'] == sha(b'') and row['nlink'] == 1, 'unsafe_lock')
            guard.verify_file(name, row)
    for row in proof['verifiedLinks']:
        name = RELEASE + '/' + row['path']
        kind, snap = guard.leaves[name]
        need(kind == stat.S_IFLNK and dict(snap, path=row['path']) == {k: row[k] for k in STAT}, 'snapshot_changed')
        with guard.directory(posixpath.dirname(name)) as fd:
            need(os.readlink(posixpath.basename(name), dir_fd=fd) == row['target'], 'link_changed')
    validate_links(proof)
    guard.recheck()


def make_private_directory(guard: Guard, name: str) -> None:
    """Exclusively create and durably track one new private audit directory."""
    parent, leaf = posixpath.split(name)
    with guard.directory(parent) as fd:
        guard.check_listing(parent, fd)
        need(leaf not in guard.listings[parent], 'namespace_collision')
        os.mkdir(leaf, 0o700, dir_fd=fd)
        child = os.open(leaf, DIRECTORY_FLAGS, dir_fd=fd)
        try:
            guard.metadata(name, os.fstat(child), private=True)
            need(os.fstat(child).st_dev == guard.dirs[parent]['device'], 'cross_device')
            guard.dirs[name] = record(name, os.fstat(child))
            guard.listings[name] = set()
            need(not guard.names(child), 'namespace_collision')
            guard.changed(parent, fd, added={leaf}, removed=set())
            os.fsync(child)
            os.fsync(fd)
        finally:
            os.close(child)


def make_marker(guard: Guard, audit: str) -> str:
    """The first write is an exclusive permanent stop marker, never reused."""
    need(MARKER not in guard.listings[audit], 'normalization_already_attempted')
    name = audit + '/' + MARKER
    make_private_directory(guard, name)
    return name


def journal_directory(marker: str, index: int) -> str:
    """Keep exact-listing checks bounded to a small shard, not a growing flat audit."""
    return marker + f'/items-{index // GROUP_SIZE:04d}'


def apply_file(guard: Guard, marker: str, index: int, action: dict) -> dict:
    """Detach or quarantine one exact inode after a durable independent backup."""
    row, backup = action['original'], action['backup']
    name = RELEASE + '/' + row['path']
    guard.verify_file(backup['path'], backup)
    with guard.regular(name, row) as (fd, parent, leaf, info):
        need(guard.hash_fd(fd, row['size']) == row['sha256'], 'hash_changed')
        bucket = journal_directory(marker, index)
        stage_name = bucket + f'/stage-{index:06d}'
        staged = None
        if action['action'] == 'isolate':
            staged = guard.create(stage_name, source=fd, original=row, stage=True, atime=info.st_atime_ns)
            need((staged['device'], staged['inode']) != (row['device'], row['inode']), 'backup_alias')
        # Do not reuse the earlier descriptor check after copying or metadata work.
        guard.verify_file(name, row)
        guard.verify_file(backup['path'], backup)
        parent_name = posixpath.dirname(name)
        with guard.directory(parent_name) as reopened:
            need(record(parent_name, os.fstat(reopened)) == record(parent_name, os.fstat(parent)), 'namespace_changed')
            guard.check_listing(parent_name, parent)
            if staged:
                guard.verify_file(stage_name, staged)
                with guard.directory(bucket) as audit_fd:
                    guard.check_listing(bucket, audit_fd)
                    guard.verify_file(name, row)
                    os.replace(posixpath.basename(stage_name), leaf, src_dir_fd=audit_fd, dst_dir_fd=parent)
                    del guard.leaves[stage_name]
                    guard.changed(bucket, audit_fd, added=set(), removed={posixpath.basename(stage_name)})
                    os.fsync(audit_fd)
                change = guard.changed(parent_name, parent, added=set(), removed=set())
                after = record(row['path'], os.stat(leaf, dir_fd=parent, follow_symlinks=False))
                need(all(after[k] == staged[k] for k in STAT - {'path', 'ctimeNs'}), 'replacement_changed')
                replacement = dict(after, sha256=row['sha256'])
                guard.leaves[name] = (stat.S_IFREG, dict(after, path=name))
                guard.verify_file(name, replacement)
            else:
                guard.verify_file(name, row)
                os.unlink(leaf, dir_fd=parent)
                del guard.leaves[name]
                change = guard.changed(parent_name, parent, added=set(), removed={leaf})
                replacement = None
            os.fsync(parent)
        old = record(row['path'], os.fstat(fd))
        need(old['nlink'] == row['nlink'] - 1 and all(old[k] == row[k] for k in STAT - {
            'ctimeNs', 'nlink'}) and guard.hash_fd(fd, row['size']) == row['sha256'] and
             record(row['path'], os.fstat(fd)) == old, 'original_alias_changed')
        return {'action': action['action'], 'original': row, 'backup': backup, 'replacement': replacement,
                'detachedOriginal': old, 'directory': change}


def apply_directory(guard: Guard, path: str) -> dict:
    """Remove only an explicitly proved generated directory with no remaining children."""
    name = RELEASE + '/' + path
    with guard.directory(name) as child:
        guard.check_listing(name, child)
        need(not guard.listings[name], 'quarantine_directory_not_empty')
        before = guard.dirs[name]
        parent, leaf = posixpath.split(name)
        with guard.directory(parent) as fd:
            guard.check_listing(parent, fd)
            need(record(name, os.stat(leaf, dir_fd=fd, follow_symlinks=False)) == before, 'snapshot_changed')
            os.rmdir(leaf, dir_fd=fd)
            del guard.dirs[name], guard.listings[name]
            change = guard.changed(parent, fd, added=set(), removed={leaf})
            os.fsync(fd)
    return {'action': 'remove-empty-generated-directory', 'original': before, 'directory': change}


def _normalize(root: Path, release: Path, audit: Path, proof: dict) -> dict:
    """Shared implementation; production never takes root from untrusted data."""
    need(os.geteuid() == ROOT_UID, 'root_required')
    need(isinstance(root, Path) and root.is_absolute() and '..' not in root.parts, 'unsafe_root')
    need(isinstance(release, Path) and release == root / RELEASE and isinstance(audit, Path) and
         audit.parent == root / OP and audit.name.startswith('continuation-'), 'fixed_paths_required')
    audit_id = audit.name[len('continuation-'):]
    need(str(uuid.UUID(audit_id)) == audit_id, 'audit_uuid')
    proof = validate_proof(proof, root)
    budget = Budget()
    guard = Guard(root, proof, budget)
    try:
        audit_name = OP + '/' + audit.name
        preflight(guard, audit_name)
        proof_bytes = encoded(proof)
        planned: list[dict] = ([{'action': 'isolate', 'original': r} for r in proof['verifiedFiles'] if r['nlink'] > 1] +
                               [{'action': 'quarantine-bytecode', 'original': r} for r in proof['quarantineBytecode']])
        group_count = (len(planned) + len(proof['quarantineDirectories']) + GROUP_SIZE - 1) // GROUP_SIZE
        need(len(guard.dirs) + len(guard.leaves) + len(planned) * 3 +
             len(proof['quarantineDirectories']) + group_count + 6 <= MAX_NODES, 'node_limit')
        # Last namespace/snapshot check immediately before the first write.
        guard.recheck()
        marker = make_marker(guard, audit_name)
        guard.json(marker + '/intent.json', {
            'schemaVersion': 1, 'operationId': OPERATION_ID, 'releaseId': RELEASE_ID,
            'auditId': audit.name, 'proofSha256': sha(proof_bytes), 'actions': len(planned),
            'quarantineDirectories': proof['quarantineDirectories'], 'executionAuthorized': False,
            'limits': {'nodes': MAX_NODES, 'actions': MAX_ACTIONS, 'fileBytes': MAX_FILE,
                       'backupBytes': MAX_BACKUP_BYTES, 'ioBytes': MAX_BYTES,
                       'jsonBytes': MAX_JSON, 'seconds': MAX_SECONDS}})
        guard.create(marker + '/proof.json', data=proof_bytes)
        for group in range(group_count):
            make_private_directory(guard, journal_directory(marker, group * GROUP_SIZE))
        for index, action in enumerate(planned):
            row = action['original']
            name = RELEASE + '/' + row['path']
            with guard.regular(name, row) as (fd, _, _, _):
                action['backup'] = guard.create(journal_directory(marker, index) + f'/backup-{index:06d}.bytes', source=fd, original=row)
            need((action['backup']['device'], action['backup']['inode']) != (row['device'], row['inode']), 'backup_alias')
            guard.verify_file(name, row)
            guard.json(journal_directory(marker, index) + f'/backup-{index:06d}.json', action)
        evidence = guard.json(marker + '/evidence.json', {
            'proofSha256': sha(proof_bytes), 'actions': planned,
            'quarantineDirectories': [r for r in proof['assertions']['ownedDirectories']
                                     if r['path'] in proof['quarantineDirectories']]})
        guard.recheck()
        applied = []
        for index, action in enumerate(planned):
            item = apply_file(guard, marker, index, action)
            guard.json(journal_directory(marker, index) + f'/applied-{index:06d}.json', item)
            applied.append(item)
        for path in proof['quarantineDirectories']:
            item = apply_directory(guard, path)
            guard.json(journal_directory(marker, len(applied)) + f'/applied-{len(applied):06d}.json', item)
            applied.append(item)
        changed = {item['original']['path']: item['replacement'] for item in applied if item['action'] == 'isolate'}
        for row in proof['verifiedFiles']:
            guard.verify_file(RELEASE + '/' + row['path'], changed.get(row['path'], row))
        guard.recheck()
        result = {
            'schemaVersion': 1, 'status': 'normalized', 'operationId': OPERATION_ID, 'releaseId': RELEASE_ID,
            'auditId': audit.name, 'proofSha256': sha(proof_bytes), 'evidenceSha256': evidence['sha256'],
            'isolatedFiles': len(changed), 'quarantinedBytecode': len(proof['quarantineBytecode']),
            'removedGeneratedDirectories': len(proof['quarantineDirectories']), 'appliedActions': len(applied),
            'executionAuthorized': False, 'requiresReverification': True, 'requiresExplicitSeal': True}
        guard.json(marker + '/applied.json', result)
        guard.recheck()
        return result
    finally:
        guard.close()


def normalize(release: Path, audit: Path, proof: dict) -> dict:
    """Production entry point; paths/proof come only from the fixed trusted wrapper."""
    return _entry(Path('/'), release, audit, proof)


def normalize_for_test(root: Path, release: Path, audit: Path, proof: dict) -> dict:
    """Explicit local-fixture injection, never a CLI/env-selected production root."""
    need(isinstance(root, Path) and root != Path('/'), 'test_root_required')
    return _entry(root, release, audit, proof)


def _entry(root: Path, release: Path, audit: Path, proof: dict) -> dict:
    """Keep OS/error text out of receipts; partial state is never retried or removed."""
    try:
        return _normalize(root, release, audit, proof)
    except Refused:
        raise
    except (OSError, ValueError, TypeError, KeyError, AttributeError, OverflowError, RecursionError):
        raise Refused('invalid_input_or_io_failure') from None
