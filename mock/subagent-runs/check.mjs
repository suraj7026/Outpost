import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { fileURLToPath } from 'node:url';
const root = new URL('./', import.meta.url);
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1568, height: 1000 }, colorScheme: 'dark', reducedMotion: 'reduce' });
  const errors = [], external = [];
  page.on('pageerror', error => { errors.push(error.message); console.error(error.message); });
  await page.route(/^https?:/, route => { external.push(route.request().url()); return route.abort(); });
  await page.goto(new URL('index.html', root).href);
  const card = page.locator('.subagent-card');
  await card.waitFor({ timeout: 15000 });
  await page.evaluate(() => document.fonts.ready);
  await page.locator('#app-sidebar[data-motion="open"]').waitFor();
  const capture = name => page.screenshot({ path: fileURLToPath(new URL(`${name}.png`, root)), animations: 'disabled' });
  assert.equal(await card.getAttribute('open'), null);
  await capture('collapsed');
  await card.locator(':scope > summary').click();
  await card.locator('.subagent-card-body').waitFor();
  await card.scrollIntoViewIfNeeded();
  await capture('expanded');
  await card.getByRole('button', { name: 'Copy summary', exact: true }).click();
  await card.locator('.subagent-card-notice').filter({ hasText: /copied|unavailable/i }).waitFor();
  await page.waitForFunction(() => !document.querySelector('.subagent-card-notice')?.textContent);
  await card.getByRole('button', { name: 'Open run', exact: true }).click();
  const panel = page.getByRole('complementary', { name: 'Subagent run details' });
  await panel.waitFor();
  assert.equal(await panel.locator('.subagent-tool').count(), 6);
  await panel.locator('.subagent-tool').filter({ hasText: 'Run startup navigation tests' }).locator('summary').click();
  await capture('run-details');
  await panel.getByRole('button', { name: 'Result', exact: true }).click();
  assert.match(await panel.locator('.subagent-result').innerText(), /436 assertions passed/);
  await panel.getByRole('button', { name: 'Activity', exact: true }).click();
  await panel.getByRole('button', { name: 'Expand run', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Expanded subagent run' });
  await dialog.waitFor();
  await dialog.locator('.subagent-tool').filter({ hasText: 'Run startup navigation tests' }).locator('summary').click();
  await capture('full-run');
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'detached' });
  await panel.waitFor();
  await panel.getByRole('button', { name: 'Close subagent run', exact: true }).click();
  assert.equal(await page.locator('.subagent-run-panel').count(), 0);
  await page.waitForFunction(() => document.activeElement?.classList.contains('subagent-open-run'));
  await page.getByRole('combobox', { name: 'Preview subagent state' }).selectOption('running');
  await card.getByRole('button', { name: 'Open run', exact: true }).click();
  await panel.locator('.subagent-tool[data-state="running"] summary').click();
  await capture('running');
  assert.equal(await panel.locator('.subagent-spin').first().evaluate(el => getComputedStyle(el).animationName), 'none', 'Reduced motion stops the spinner');
  await panel.getByRole('button', { name: 'Stop subagent', exact: true }).click();
  await panel.getByText('Stopped', { exact: true }).first().waitFor();
  assert.equal(await panel.getByRole('button', { name: 'Stop subagent', exact: true }).count(), 0);
  await page.getByRole('combobox', { name: 'Preview subagent state' }).selectOption('failed');
  if (await panel.locator('.subagent-tool[data-state="failed"]').getAttribute('open') === null) await panel.locator('.subagent-tool[data-state="failed"] summary').click();
  await panel.locator('.subagent-tool[data-state="failed"]').scrollIntoViewIfNeeded();
  await capture('failed');
  assert.match(await panel.locator('.subagent-tool[data-state="failed"]').innerText(), /AssertionError/);
  await page.getByRole('button', { name: 'Close subagent panel', exact: true }).click();
  assert.equal(await page.locator('.subagent-run-panel').count(), 0);
  await page.getByRole('combobox', { name: 'Preview subagent state' }).selectOption('completed');
  await card.getByRole('button', { name: 'Open run', exact: true }).click();
  await page.setViewportSize({ width: 1000, height: 900 });
  assert.equal(await page.locator('.conversation-column').isVisible(), false);
  await capture('run-details-1000');
  await page.mouse.move(950, 400);
  if (await page.locator('#app-sidebar').getAttribute('aria-hidden') !== 'true') await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).evaluate(el => el.click());
  await page.locator('#app-sidebar[data-motion="closed"]').waitFor({ state: 'attached' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.mouse.move(380, 400);
  await capture('run-details-390');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await panel.getByRole('button', { name: 'Close subagent run', exact: true }).click();
  assert.equal(await page.locator('.conversation-column').isVisible(), true);
  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
  assert.deepEqual(await page.evaluate(() => window.__subagentPreview.blocked), []);
  console.log('PASS: collapse/expand, result/activity views, tool output disclosures, full run, state previews, stop simulation, focus return, narrow layouts, reduced motion; no network or real subagent commands.');
} finally { await browser.close(); }
